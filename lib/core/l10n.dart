import 'package:flutter/widgets.dart';

class L10n {
  const L10n(this.language);

  final String language;

  static const supportedLocales = [Locale('en'), Locale('ar')];

  static Set<String> get englishKeys => _en.keys.toSet();

  static Set<String> get arabicKeys => _ar.keys.toSet();

  bool get isArabic => language == 'ar';

  String t(String key) => (isArabic ? _ar[key] : _en[key]) ?? _en[key] ?? key;

  String f(String key, Map<String, String> values) {
    var text = t(key);
    values.forEach((name, value) => text = text.replaceAll('{$name}', value));
    return text;
  }

  String month(int month) => (isArabic ? _arMonths : _enMonths)[(month - 1).clamp(0, 11)];

  String weekday(int weekday) => (isArabic ? _arWeekdays : _enWeekdays)[weekday % 7];
}

class L10nScope extends InheritedWidget {
  const L10nScope({super.key, required this.l10n, required super.child});

  final L10n l10n;

  static L10n of(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<L10nScope>()?.l10n ?? const L10n('en');

  @override
  bool updateShouldNotify(L10nScope oldWidget) => oldWidget.l10n.language != l10n.language;
}

extension L10nContext on BuildContext {
  L10n get l10n => L10nScope.of(this);

  String t(String key) => l10n.t(key);
}

